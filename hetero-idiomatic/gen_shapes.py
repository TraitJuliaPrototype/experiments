# Writes shapes_defs.jl (python3 gen_shapes.py): the shape types and traits of hi2_shapes.jl.
ns = (2, 4, 5, 8, 64)
L = ["# Generated by gen_shapes.py: 64 shape types, the plain twin (an abstract type and one function per n with",
     "# n methods), and five traits S2, S4, S5, S8, S64 with exactly n implementations each. Included by hi2_shapes.jl.",
     "abstract type AShape end"]
L += [f"struct P{i} <: AShape; a::Float64; end" for i in range(1, 65)]
for n in ns:
    L += [f"parea{n}(s::P{i}) = {float(i)} * s.a" for i in range(1, n + 1)]
L += [f"ptotal{n}(v::Vector{{AShape}}) = (s = 0.0; for x in v; s += parea{n}(x); end; s)" for n in ns]
L += ["", "@trait_module module ShapeCore", "using TraitWorld",
      "using ..Main: AShape, " + ", ".join(f"P{i}" for i in range(1, 65)) + ", " + ", ".join(f"parea{n}" for n in ns),
      "export " + ", ".join(f"S{n}, area{n}, total{n}, itotal{n}" for n in ns)]
for n in ns:
    L += [f"@trait S{n} begin", f"    area{n}(s::S{n})::Float64", "end"]
    L += [f"@implement S{n} P{i} begin area{n}(s) = {float(i)} * s.a end" for i in range(1, n + 1)]
    L += [f"total{n}(xs::Iterable{{S{n}}}) = (s = 0.0; for x in xs; s += area{n}(x); end; s)",
          "# interop: trait code calling the plain twin on the user's abstractly typed vector",
          f"itotal{n}(v::Vector{{AShape}}) = (s = 0.0; for x in v; s += parea{n}(x); end; s)"]
L += ["end", "using .ShapeCore"]
open("shapes_defs.jl", "w").write("\n".join(L) + "\n")
