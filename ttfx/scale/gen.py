# E-171: generate trait packages of three sizes (python3 gen.py). Package ScaleX: a trait module with K traits of
# three operations each, N types implementing every trait, M bounded functions (each over one trait), and a
# workload calling every function on every type: N*M workers compiled into the image.
import os, uuid
SIZES = {"S": (4, 2, 8), "M": (12, 4, 32), "L": (40, 8, 100)}   # N types, K traits, M functions
for name, (N, K, M) in SIZES.items():
    pkg = f"Scale{name}"; os.makedirs(f"{pkg}/src", exist_ok=True)
    u = uuid.uuid5(uuid.NAMESPACE_DNS, pkg)
    open(f"{pkg}/Project.toml", "w").write(f'''name = "{pkg}"
uuid = "{u}"
version = "0.0.1"

[deps]
TraitWorld = "7a3c1e52-9b4d-4f6e-8a21-5d0c3b9e7f14"

[sources]
TraitWorld = {{path = "../../../../TraitWorld"}}
''')
    L = [f"# Generated by gen.py (E-171): N = {N} types, K = {K} traits, M = {M} bounded functions, {N*M} workers.",
         f"module {pkg}", "using TraitWorld", "export Core_", "",
         "@trait_module module Core_", "using TraitWorld",
         "export " + ", ".join([f"Tr{k}" for k in range(1, K+1)] + [f"T{i}" for i in range(1, N+1)] + [f"f{j}" for j in range(1, M+1)])]
    for k in range(1, K+1):
        L += [f"@trait Tr{k} begin", f"    a{k}(x::Tr{k})::Float64", f"    b{k}(x::Tr{k}, y::Float64)::Float64", f"    c{k}(x::Tr{k})::Vector{{Float64}}", "end"]
    for i in range(1, N+1):
        L += [f"struct T{i}; v::Float64; w::Vector{{Float64}}; end"]
        for k in range(1, K+1):
            L += [f"@implement Tr{k} T{i} begin", f"    a{k}(x) = {i}.0 * x.v + {k}.0", f"    b{k}(x, y) = x.v * y + {i*k}.0",
                  f"    c{k}(x) = x.w .* {k}.0", "end"]
    for j in range(1, M+1):
        k = (j - 1) % K + 1
        L += [f"function f{j}(x::Tr{k}, n::Int)", "    s = 0.0", "    for t in 1:n",
              f"        s += a{k}(x) + b{k}(x, Float64(t)) * {j}.0", f"        s += sum(c{k}(x))", "    end", "    return s", "end"]
    L += ["@workload begin"]
    L += [f"    let x = T{i}(1.0, [1.0, 2.0])" + "".join(f"; f{j}(x, 2)" for j in range(1, M+1)) + " end" for i in range(1, N+1)]
    L += ["end", "end", "using .Core_", "end"]
    open(f"{pkg}/src/{pkg}.jl", "w").write("\n".join(L) + "\n")
    print(pkg, N, K, M, N*M, "workers;", len(L), "lines")
